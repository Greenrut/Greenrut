import { config } from '../config/env.js'
import { Account } from '../models/Account.js'
import { Order } from '../models/Order.js'
import { createHttpError } from '../utils/httpError.js'
import { seedAccountForUser } from './accountController.js'
import { verifyToken } from '../utils/auth.js'

function getBearerToken(req) {
  const header = req.headers.authorization || ''
  const [scheme, token] = header.split(' ')

  if (scheme !== 'Bearer' || !token) {
    return null
  }

  return token
}

function getOptionalAuthPayload(req) {
  const token = getBearerToken(req)
  if (!token) return null

  return verifyToken(token, config.jwtSecret)
}

function normalizeItems(items = []) {
  if (!Array.isArray(items)) return []

  return items
    .map((item) => ({
      name: String(item?.name || item?.title || 'Item').trim(),
      quantity: Number(item?.quantity || item?.qty || 1) || 1,
      price: Number(item?.price || item?.subtotal || 0) || 0,
    }))
    .filter((item) => item.name)
}

export function getPaystackConfig(req, res) {
  const key = config.paystack.publicKey || process.env.PAYSTACK_PUBLIC_KEY || ''
  res.json({
    ok: true,
    publicKey: key,
    isLive: Boolean(key && key.startsWith('pk_live_')),
  })
}

async function verifyWithPaystack(reference) {
  // ── Mock / development mode ─────────────────────────────────────────────
  // If no secret key is configured and the reference is a local mock
  // reference (generated by the dev-mode Paystack simulation modal),
  // return a synthetic success payload so the full checkout flow can be
  // tested without real Paystack credentials.
  if (!config.paystack.secretKey && String(reference).startsWith('GR-MOCK-')) {
    return {
      status: 'success',
      amount: 0,          // amount is read from the cart on the client; 0 is fine for mock
      currency: 'NGN',
      reference,
      paid_at: new Date().toISOString(),
      customer: { email: '' },
    }
  }

  if (!config.paystack.secretKey) {
    throw createHttpError(500, 'Paystack secret key is not configured')
  }

  const response = await fetch(`https://api.paystack.co/transaction/verify/${encodeURIComponent(reference)}`, {
    headers: {
      Authorization: `Bearer ${config.paystack.secretKey}`,
      Accept: 'application/json',
    },
  })

  const payload = await response.json().catch(() => null)
  if (!response.ok || !payload?.status) {
    throw createHttpError(502, payload?.message || 'Unable to verify payment with Paystack')
  }

  return payload.data
}

export async function verifyPaystackPayment(req, res, next) {
  try {
    const reference = String(req.body?.reference || req.query?.reference || '').trim()
    const items = normalizeItems(req.body?.items || [])
    const fallbackEmail = String(req.body?.email || '').trim()

    if (!reference) {
      return next(createHttpError(400, 'Payment reference is required'))
    }

    const verification = await verifyWithPaystack(reference)

    if (String(verification.status || '').toLowerCase() !== 'success') {
      return next(createHttpError(400, 'Payment was not successful'))
    }

    const amount = Number(verification.amount || 0) / 100
    const currency = String(verification.currency || 'NGN').toUpperCase()
    const customerEmail = String(verification.customer?.email || fallbackEmail || '').trim()
    const authPayload = getOptionalAuthPayload(req)

    let order = null
    const productSummary = items.length
      ? items.map((item) => `${item.name}${item.quantity > 1 ? ` (x${item.quantity})` : ''}`).join(', ')
      : 'Cart checkout'

    let account = null
    if (authPayload?.sub) {
      account = await seedAccountForUser(authPayload.sub)
    }

    const orderCount = await Order.countDocuments()
    const orderNumber = orderCount + 1001

    order = await Order.create({
      orderNumber,
      userId: authPayload?.sub || null,
      accountId: account?._id || null,
      customerName: account?.profile ? `${account.profile.firstName || ''} ${account.profile.lastName || ''}`.trim() : (verification.customer?.name || ''),
      customerEmail: customerEmail || account?.profile?.email || 'customer@greenrut.com',
      customerPhone: account?.profile?.phone || '',
      items: items.map((i) => ({
        name: i.name,
        quantity: i.quantity || 1,
        price: i.price || 0,
        image: i.image || '',
      })),
      productSummary,
      total: amount,
      currency,
      paymentReference: reference,
      paymentGateway: 'Paystack',
      status: 'Paid',
      paidAt: new Date(verification.paid_at || Date.now()),
    })

    if (account) {
      account.orders.push({
        _id: order._id,
        orderNumber: order.orderNumber,
        product: productSummary,
        date: order.createdAt || new Date(),
        status: 'Paid',
        total: amount,
        paymentReference: reference,
        paymentGateway: 'Paystack',
        currency,
        customerEmail,
        paidAt: order.paidAt,
        items: order.items,
      })
      await account.save()
    }

    res.json({
      ok: true,
      data: {
        reference,
        amount,
        currency,
        email: customerEmail,
        status: verification.status,
        gateway: 'Paystack',
        order,
      },
    })
  } catch (error) {
    next(error)
  }
}
